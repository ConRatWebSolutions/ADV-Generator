</p>
<p>
    10.5 ConRat verpflichtet sich, dem Kunde auf Anforderung die zur Wahrung seiner bei der Verarbeitung der oben genannten
</p>
<p>
    Daten bestehende Verpflichtung zur Auftragskontrolle erforderlichen Auskünfte zu geben und Nachweise zu führen. Dies gilt
</p>
<p>
    auch, soweit ConRat die Kontrolle seiner Unterauftragnehmer für den Kunde durchführt.
