<p>
    <strong>1. Gegenstand des Vertrages, Gegenstand dieses Auftragsverarbeitungsvertrages (Art. 28 Abs. 1 DSGVO)</strong>
</p>
<p>
    1.1 Gegenstand des Vertrages ist die Bereitstellung von Webhosting-Dienstleistungen sowie der damit im Zusammenhang stehenden Leistungen wie z.B. E-Mail, Domainregistrierung, etc. Im Rahmen dieses Vertrages hat der Kunde – je nach Tarif und vereinbartem Leistungsumfang – unter Nutzung u.a. z.B. eines Webservers, FTP-Servers oder SSH-Zugangs die Möglichkeit, Daten zu verarbeiten (zu speichern, zu verändern, zu übermitteln und zu löschen).
</p>
<p>
    1.2 Gegenstand des Vertrages ist nicht<strong> </strong>die originäre Nutzung oder Verarbeitung von personenbezogenen Daten durch ConRat.
</p>
<p>
    Im Zuge der Leistungserbringung von ConRats als zentraler IT- Dienstleister im Bereich des Hostings, des Supports bzw. der Administration von Server-Systemen des Kundes, kann ein Zugriff auf personenbezogene Daten jedoch nicht ausgeschlossen werden.
</p>
<p>
    1.3 Die Einzelheiten ergeben sich aus dem Hostingvertrag zwischen dem Kunden und ConRat. Die Vereinbarung zur Auftragsverarbeitung findet Anwendung auf das gesamte Dienstleistungsverhältnis, sofern die in Punkt 1.1 beschriebenen Dienstleistungen betroffen sind.
</p>
<p>
    1.4 Soweit nachfolgend von Daten die Rede ist, handelt es sich ausschließlich um personenbezogene Daten im Sinne der
</p>
<p>
    DSGVO. Die nachfolgenden Datenschutz- und Datensicherheitsbestimmungen finden Anwendung auf alle Leistungen der
</p>
<p>
    Auftragsverarbeitung i.S.d. Art. 28 Abs. 1 DSGVO, die der ConRat gegenüber dem Kunde erbringt und auf alle Tätigkeiten, bei
</p>
<p>
    denen Mitarbeiter ConRats oder durch ConRat beauftragte Dritte mit personenbezogenen Daten des Kundes in Berührung
</p>
<p>
    kommen können.
</p>
<p>
    1.5 In Ergänzung<strong> </strong>zu dem/den zwischen den Parteien geschlossenen Vertrag/Verträgen konkretisieren die Vertragsparteien mit
</p>
<p>
    vorliegendem Auftragsverarbeitungsvertrag die gegenseitigen Pflichten im generellen Umgang mit den Daten des Kundes.
</p>
<p>
    <strong>2. Laufzeit, Beendigung, Löschung von Daten (Art. 28 Abs. 1 DSGVO)</strong>
</p>
<p>
    2.1 Die Laufzeit des Vertrages richtet sich nach der Dauer der Erbringung von Hosting-Leistungen ConRats an den Kunde. Der
</p>
<p>
    Auftrag endet, wenn der Kunde keine Hosting-Leistungen ConRats mehr in Anspruch nimmt.
</p>
<p>
    2.2 Die Rechte der durch den Datenumgang bei ConRat betroffenen Personen, insbesondere auf Berichtigung, Löschung und
</p>
<p>
    Sperrung, sind gegenüber dem Kunde geltend zu machen. Er, der Kunde, ist allein verantwortlich für die Wahrung dieser
</p>
<p>
    Rechte.
</p>
<p>
    2.3 Nach Ende des Auftrags oder auf schriftliche Aufforderung durch den Kunde hat ConRat sämtliche Daten des Kundes
</p>
<p>
    vollständig datenschutzgerecht zu löschen (einschließlich der verfahrens- oder sicherheitstechnisch notwendigen Kopien) oder
</p>
<p>
    an den Kunde zurückzugeben. Das gleiche gilt auch für Test- und Ausschussmaterial, das bis zur Löschung oder Rückgabe
</p>
<p>
    unter datenschutzgerechtem Verschluss zu halten ist. Dies gilt nicht für Dokumentationen, die dem Nachweis der auftrags- und
</p>
<p>
    ordnungsgemäßen Datenverarbeitung dienen oder soweit z.B. rechtliche Regelungen, gesetzliche Pflichten oder gerichtliche
</p>
<p>
    Verfügungen dem entgegenstehen. Entstehen durch eine Löschung vor Vertragsbeendigung zusätzliche Kosten, so trägt diese
</p>
<p>
    der Kunde.
</p>
<p>
    2.4 ConRat ist verpflichtet, im Rahmen seiner Tätigkeit für den Kunde an ihn gerichtete Ersuchen Betroffener zur sachgerechten
</p>
<p>
    Bearbeitung unverzüglich an die Kunde weiterzuleiten. Er ist nicht berechtigt, diese Ersuchen ohne Abstimmung mit dem Kunde
</p>
<p>
    selbständig zu bescheiden
</p>
<p>
    2.5 ConRat hat den Kunde bei der Umsetzung der Rechte der Betroffenen nach Kapitel III der DSGVO, insbesondere im
</p>
<p>
    Hinblick auf Berichtigung, Sperrung und Löschung, Benachrichtigung und Auskunftserteilung, im Rahmen der technischen
</p>
<p>
    Möglichkeiten, insbesondere hinsichtlich des Charakters der geschuldeten Dienstleistung, zu unterstützen
</p>
<p>
    2.6 Zu einem Datenträgeraustausch gemäß Art. 28 Abs. 3 lit. g DSGVO zwischen den Beteiligten dieser Auftragsverarbeitung
</p>
<p>
    kommt es nicht. Insoweit ist eine Rückgabe nicht zu regeln.
</p>
