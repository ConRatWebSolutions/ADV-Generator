</p>
<p>
    8.3 Erteilt ConRat Aufträge an Unternehmen (Unterauftragnehmer), so obliegt es ConRat, seine Pflichten aus diesem
</p>
<p>
    Auftragsverarbeitungsvertrag dem Unterauftragnehmer zu übertragen.
</p>
<p>
    <strong>9. Weisungsbefugnisse, Berichtigung, Löschung und Sperrung, Rechte Betroffener</strong>
</p>
<p>
    9.1. Der Kunde hat selbst jederzeit umfassenden Zugriff auf die Daten, so dass es einer Mitwirkung von ConRat insbesondere
</p>
<p>
    auch zur Berichtigung, Sperrung, Löschung etc. nicht bedarf. Soweit eine Mitwirkung von ConRat erforderlich ist, ist ConRat
</p>
<p>
    hierzu gegen Erstattung der anfallenden Kosten verpflichtet. Dem Kunden steht in diesem Fall ein umfassendes Weisungsrecht
</p>
<p>
    über Art, Umfang und Verfahren der Datenverarbeitung gem. Art. 29 i.V.m. 28 DSGVO zu. ConRat hat den Kunde unverzüglich
</p>
<p>
    zu informieren, wenn ConRat der Meinung ist, eine Weisung verstoße gegen datenschutzrechtliche Vorschriften. ConRat ist
</p>
<p>
    berechtigt, die Durchführung der entsprechenden Weisung solange auszusetzen, bis Sie durch den Verantwortlichen beim
</p>
<p>
    Kunden bestätigt oder geändert wird.
</p>
<p>
    9.2. Soweit ein Betroffener sich unmittelbar an ConRat zwecks Berichtigung oder Löschung seiner Daten wenden sollte, wird
</p>
<p>
    &nbsp;ConRat dieses Ersuchen an den Kunde weiterleiten. Ist der Kunde auf Grund geltender Datenschutzgesetzte verpflichtet,
</p>
<p>
    Auskünfte zur Erhebung, Verarbeitung und / oder Nutzung von Daten zu erteilen, wird ConRat den Kunde soweit notwendig bei
</p>
<p>
    der Bereitstellung dieser Informationen unterstützen. Eine diesbezgl. Anfrage hat der Kunde schriftlich an ConRat zu richten
</p>
<p>
    und ConRat die entstandenen Kosten zu erstatten.
</p>
