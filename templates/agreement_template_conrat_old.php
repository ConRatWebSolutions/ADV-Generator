    <strong>3. Umfang, Art und Zweck der vorgesehenen Erhebung, Verarbeitung und / oder Nutzung der Daten</strong>
</p>
<p>
    3.1 Umfang, Art und Zweck der vorgesehenen Erhebung, Verarbeitung und / oder Nutzung der Daten ergeben sich aus dem
</p>
<p>
    zwischen den Parteien bestehenden Vertrag.
</p>
<p>
    ConRat ist verpflichtet, die ihm zur Verfügung gestellten personenbezogenen Daten ausschließlich zur vertraglich vereinbarten
</p>
<p>
    Leistung zu verwenden. ConRat ist es gestattet, verfahrens- und sicherheitstechnisch erforderliche Zwischen-, Temporär- oder
</p>
<p>
    Duplikatsdateien zur leistungsgemäßen Erhebung, Verarbeitung und / oder Nutzung der personenbezogenen Daten zu
</p>
<p>
    erstellen, soweit dies nicht zu einer inhaltlichen Umgestaltung führt. ConRat ist nicht gestattet, unautorisiert Kopien der
</p>
<p>
    personenbezogenen Daten zu erstellen.
</p>
<p>
    Der Kunde informiert den ConRat unverzüglich, wenn er Fehler oder Unregelmäßigkeiten bei der Prüfung der
</p>
<p>
    Auftragsergebnisse feststellt.
</p>
<p>
    3.2 Soweit seitens ConRat eine Erhebung, Verarbeitung und / oder Nutzung der Daten erfolgt, geschieht dies ausschließlich im
</p>
<p>
    Gebiet der Bundesrepublik Deutschland, in einem Mitgliedsstaat der Europäischen Union oder in einem anderen Vertragsstaat
</p>
<p>
    des Abkommens über den Europäischen Wirtschaftsraum. Jede Verlagerung in ein anderes Drittland bedarf der vorherigen
</p>
<p>
    Zustimmung des Kunden und darf nur erfolgen, wenn die besonderen Voraussetzungen der Art. 44 DSGVO erfüllt sind.
</p>
<p>
    <strong>4. Art der Daten und Kreis der Betroffenen (Art. 28 Abs. 3 S. 1 DSGVO)</strong>
</p>
<p>
    4.1 Gegenstand der Erhebung, Verarbeitung und / oder Nutzung der Daten des Kunden gem. Ziff. 1.2 Satz 2 sind folgende
</p>
<p>
    Datenarten: Personenstammdaten, Kommunikationsdaten (z.B. Telefon, E-Mail), Vertragsstammdaten (Vertragsbeziehung,
</p>
<p>
    Produkt- bzw. Vertragsinteresse), Kundenhistorie, Vertragsabrechnungs- und Zahlungsdaten.
</p>
<p>
    4.2 Der Kreis der durch den Umgang mit den Daten gem. Ziff. 1.2 Satz 2 Betroffenen umfasst: Kunden, Interessenten,
</p>
<p>
    Abonnenten, Beschäftigte, Lieferanten, Handelsvertreter und Ansprechpartner.
</p>
<p>
    <strong>5. Pflichten und Rechte des Kunden</strong>
</p>
<p>
    5.1 Der Kunde ist im Rahmen dieser Vereinbarung zur Auftragsverarbeitung für die Einhaltung der gesetzlichen Bestimmungen
</p>
<p>
    der Datenschutzgesetze, insbesondere für die Rechtmäßigkeit der Datenweitergabe an ConRat sowie für die Rechtmäßigkeit
</p>
<p>
    der Verarbeitung allein verantwortlich (»Verantwortlicher« im Sinne des Art. 4 Nr. 7 DSGVO). Dies gilt auch im Hinblick auf die in
</p>
<p>
    dieser Vereinbarung geregelten Zwecke und Mittel der Verarbeitung und die Beschreibung der betroffenen Daten.
</p>
<p>
    5.2 Der Kunde hat ConRat unverzüglich und vollständig zu informieren, wenn er im Hinblick auf die Verarbeitung bezüglich
</p>
<p>
    datenschutzrechtlicher Bestimmungen Fehler oder Unregelmäßigkeiten feststellt.
</p>
<p>
    5.3 Der Kunde nennt ConRat bei Bedarf den Ansprechpartner für im Rahmen dieser Vereinbarung zur Auftragsverarbeitung
</p>
<p>
    anfallende Datenschutzfragen.
</p>
<p>
    5.4 Weitere Pflichten und Rechte des Kunden ergeben sich aus den nachfolgenden Regelungen dieser Vereinbarung zur
</p>
<p>
    Auftragsverarbeitung und der DSGVO sowie den dazugehörigen gesetzlichen Bestimmungen.
</p>
