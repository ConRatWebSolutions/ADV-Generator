</p>
<p>
    ConRat getroffenen technischen und organisatorischen Maßnahmen zu überzeugen.
</p>
<p>
    10.2. Dem Kunde steht hierzu die durch Conrat erstellte, regelmäßig überarbeitete und den gesetzlichen Anforderungen
</p>
<p>
    entsprechende Dokumentation über die vorhandenen technischen und organisatorischen Maßnahmen zur Verfügung. Diese
</p>
<p>
    Dokumentation kann unter dem Link https://www.some-solutions.de/dsgvo-tom abgerufen werden.
</p>
<p>
    10.3. Der Kunde hat das Recht, die Auftragskontrolle im Benehmen mit ConRat durchzuführen oder durch im Einzelfall zu
</p>
<p>
    benennende Prüfer durchführen zu lassen. Er hat das Recht, sich durch Stichprobenkontrollen, nach rechtzeitiger vorheriger
</p>
<p>
    Anmeldung (3 Wochen) zu den üblichen Geschäftszeiten ohne Störung des Betriebsablaufs, von der Einhaltung dieser
</p>
<p>
    Vereinbarung durch ConRat in seinem Geschäftsbetrieb zu überzeugen. ConRat verpflichtet sich, dem Kunden auf Anforderung
</p>
<p>
    die zur Wahrung seiner Verpflichtung zur Auftragskontrolle erforderlichen Auskünfte zu geben und die entsprechenden
</p>
<p>
    Nachweise verfügbar zu machen. Kosten, die ConRat durch seine Unterstützungshandlung entstehen, sind ihm im
</p>
<p>
