</p>
<p>
    8.1 Der Kunde ist damit einverstanden, dass der ConRat zur Erfüllung seiner vertraglich vereinbarten Leistungen,
</p>
<p>
    insbesondere, aber nicht ausschließlich, für die Bereiche, Rechenzentrum, Hosting, Wartung und Installation der Infrastruktur
</p>
<p>
    und Telekommunikationsdienstleistungen weitere Unternehmen (Unterauftragnehmer) mit Leistungen beauftragt.
</p>
<p>
    8.2 Die jeweils aktuell eingesetzten, weiteren Auftragsverarbeiter kann der Kunde auf der Webseite der ConRat unter dem Link
</p>
<p>
