<p>
    <strong>7. Technische und organisatorische Maßnahmen</strong>
</p>
<p>
    7.1 ConRat gestaltet in ihrem Verantwortungsbereich die innerbetriebliche Organisation so, dass geeignete technische und
</p>
<p>
    organisatorische Maßnahmen so durchgeführt werden, dass die Verarbeitung gemäß den Anforderungen der DSGVO erfolgt
</p>
<p>
    und den Schutz für die Rechte und Freiheiten der betroffenen Person gewährleistet. ConRat trifft dabei technische und
</p>
<p>
    organisatorische Maßnahmen zur angemessenen Sicherung der Daten vor Missbrauch und Verlust, um den Anforderungen der
</p>
<p>
    DSGVO zu entsprechen. Eine Aufstellung der technischen und organisatorischen Maßnahmen kann der Kunde unter dem Link
</p>
<p>
    https://www.some-solutions.de/dsgvo-tom abrufen.
</p>
<p>
    7.2 Die Parteien sind sich einig, dass die technischen und organisatorischen Maßnahmen dem technischen Fortschritt und der
</p>
<p>
    Weiterentwicklung unterliegen. Insoweit ist es ConRat gestattet, alternative adäquate Maßnahmen umzusetzen. ConRat
</p>
<p>
    informiert den Kunde hierüber auf Anfrage und stellt sicher, dass das Sicherheitsniveau der festgelegten Maßnahme nicht
</p>
<p>
    unterschritten wird. ConRat hat die Sicherheit gem. Art. 28 Abs. 3 lit. c, 32 DSGVO insbesondere in Verbindung mit Art. 6 Abs.
</p>
<p>
    1, Abs. 2 DSGVO herzustellen. Insgesamt handelt es sich bei den zu treffenden Maßnahmen um Maßnahmen der
</p>
<p>
    Datensicherheit und zur Gewährleistung eines dem Risiko angemessenen Schutzniveaus hinsichtlich der Vertraulichkeit, der
</p>
<p>
    Integrität, der Verfügbarkeit sowie der Belastbarkeit der Systeme.
</p>
